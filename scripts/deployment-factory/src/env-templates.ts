/**
 * ENV template generator (Render API + Vercel web).
 *
 * Why this file exists:
 *   - Transcribing ~30 keys by hand across two dashboards is the #2 source of
 *     deployment time and the #1 source of silent misconfiguration
 *     (wrong JWT_SECRET fails at login, not boot; trailing-slash FRONTEND_URL
 *     breaks CORS with a confusing browser error).
 *   - The generator knows the authoritative ENV contract from
 *     docs/deployment.md §5 (NOT only apps/api/.env.example — that file is
 *     missing RESEND_WEBHOOK_SECRET, PUPPETEER_EXECUTABLE_PATH,
 *     PUPPETEER_CACHE_DIR and LIVE_SESSION_DEFAULT_HOST_ID).
 *
 * Safety guarantees (enforced by tests):
 *   - Templates contain placeholders ONLY — never real secret values.
 *     Derived non-secrets (FRONTEND_URL, NEXT_PUBLIC_API_URL) are real values.
 *   - Service-role key appears ONLY in the Render template, never Vercel.
 *   - SUPABASE_ACCESS_TOKEN* appears NOWHERE (admin tooling only).
 */

import type { ClientConfig } from './types';

export const SECRET_PLACEHOLDER = '<ENTER_IN_DASHBOARD>';
export const COPY_FROM_RENDER = '<COPY_FROM_RENDER_API_ENV>';

function header(title: string, clientName: string, deploymentId: string): string {
  return [
    '# ============================================================================',
    `# ${title}`,
    `# Client: ${clientName} (${deploymentId})`,
    '# Generated by the deployment factory (local operator tool).',
    '#',
    '# HOW TO USE (bulk paste): paste this WHOLE BLOCK into the platform dashboard.',
    '#   - Placeholders look like <...> — replace every one before deploying.',
    '#   - "GENERATED FROM CLIENT CONFIG" lines are derived — paste as-is.',
    '#   - "SECRET" lines come from client-owned dashboards/stores — never git/chat.',
    '#   - NEVER commit this file. NEVER paste secrets into git/chat/docs.',
    '# ============================================================================',
    '',
  ].join('\n');
}

function req(comment: string): string {
  return `# REQUIRED — ${comment}`;
}

function opt(comment: string): string {
  return `# OPTIONAL — ${comment}`;
}

/** Render (NestJS API) environment template. */
export function buildRenderEnvTemplate(config: ClientConfig): string {
  const { frontendDomain } = config.deployment;
  const lines: string[] = [header('Render API — environment template', config.client.name, config.client.deploymentId)];

  lines.push('# ── Application ────────────────────────────────────────────────');
  lines.push('NODE_ENV=production');
  lines.push('PORT=3001');
  lines.push(req('must EXACTLY equal the Vercel origin (scheme + host, no trailing slash).'));
  lines.push('# GENERATED FROM CLIENT CONFIG — paste as-is.');
  lines.push(`FRONTEND_URL=${frontendDomain}`);
  lines.push('');

  lines.push('# ── JWT ────────────────────────────────────────────────────────');
  lines.push(req('no default. Missing/wrong value fails at LOGIN, not boot — treat as deployment-blocking.'));
  lines.push('# SECRET — generate locally with: pnpm factory gen-secret');
  lines.push('# Paste the printed value here and into your handover record. Never store it in git.');
  lines.push(`JWT_SECRET=${SECRET_PLACEHOLDER}`);
  lines.push(opt('defaults to 24h.'));
  lines.push('JWT_EXPIRES_IN=24h');
  lines.push(opt('single = one active session per user (client default). multi is demo-only and is set manually on the demo deployment — never generated here.'));
  lines.push('SESSION_POLICY=single');
  lines.push(opt('enabled = normal self-service password flows (client default). disabled is demo-only and is set manually on the demo deployment — never generated here.'));
  lines.push('PASSWORD_MANAGEMENT=enabled');
  lines.push('');

  lines.push('# ── Supabase (client project) ────────────────────────────────');
  lines.push(req('all three from Supabase dashboard → Project Settings → API.'));
  lines.push('# SECRET — service-role bypasses RLS. API server ONLY, never the browser.');
  lines.push(`SUPABASE_URL=${SECRET_PLACEHOLDER}`);
  lines.push(`SUPABASE_SERVICE_ROLE_KEY=${SECRET_PLACEHOLDER}`);
  lines.push('# Anon key is public-by-design (browser use is expected).');
  lines.push(`SUPABASE_ANON_KEY=${SECRET_PLACEHOLDER}`);
  lines.push('');

  lines.push('# ── Redis (client instance) ──────────────────────────────────');
  lines.push(req('sessions + rate limits. Anonymous/public paths work without it; login does not.'));
  lines.push(`REDIS_HOST=${SECRET_PLACEHOLDER}`);
  lines.push(`REDIS_PORT=${SECRET_PLACEHOLDER}`);
  lines.push('# SECRET — if set, the API enables TLS. Must match the server.');
  lines.push(`REDIS_PASSWORD=${SECRET_PLACEHOLDER}`);
  lines.push('');

  if (config.providers.zoom) {
    lines.push('# ── Zoom (client account — Server-to-Server OAuth) ─────────────');
    lines.push(req('only because providers.zoom=true for this client.'));
    for (const k of ['ZOOM_ACCOUNT_ID', 'ZOOM_CLIENT_ID', 'ZOOM_CLIENT_SECRET', 'ZOOM_WEBHOOK_SECRET', 'ZOOM_SDK_KEY', 'ZOOM_SDK_SECRET']) {
      lines.push(`${k}=${SECRET_PLACEHOLDER}`);
    }
    lines.push(opt('LIVE_SESSION_DEFAULT_HOST_ID — default Zoom host for live sessions.'));
    lines.push(`LIVE_SESSION_DEFAULT_HOST_ID=${SECRET_PLACEHOLDER}`);
    lines.push('');
  } else {
    lines.push('# ── Zoom — SKIPPED (providers.zoom=false for this client) ───────');
    lines.push('# Leave all ZOOM_* unset. Endpoints throw loudly only if called.');
    lines.push('');
  }

  const video = config.providers.video;
  lines.push('# ── Video provider ─────────────────────────────────────────────');
  lines.push(`VIDEO_UPLOAD_PROVIDER=${video === 'none' ? 'bunny' : video}`);
  if (video === 'none') {
    lines.push('# providers.video=none: uploads 503 fail-visible. Leave BUNNY_* unset.');
  }
  if (video === 'bunny') {
    lines.push(req('client Bunny Stream account: library + pull zone + token auth.'));
    for (const k of ['BUNNY_ENABLED', 'BUNNY_LIBRARY_ID', 'BUNNY_API_KEY', 'BUNNY_CDN_HOSTNAME', 'BUNNY_TOKEN_SIGNING_KEY', 'BUNNY_WEBHOOK_SECRET']) {
      lines.push(k === 'BUNNY_ENABLED' ? 'BUNNY_ENABLED=true' : `${k}=${SECRET_PLACEHOLDER}`);
    }
    lines.push(opt('TTL tunables (defaults shown).'));
    lines.push('BUNNY_CDN_TOKEN_TTL_SECONDS=14400');
    lines.push('BUNNY_UPLOAD_SIGNATURE_TTL_SECONDS=86400');
  }
  if (video === 'mux') {
    lines.push(req('dormant-rollback path selected: client Mux account required.'));
    for (const k of ['MUX_TOKEN_ID', 'MUX_TOKEN_SECRET', 'MUX_SIGNING_KEY_ID', 'MUX_SIGNING_PRIVATE_KEY', 'MUX_WEBHOOK_SECRET']) {
      lines.push(`${k}=${SECRET_PLACEHOLDER}`);
    }
  }
  if (video === 'none' || video === 'bunny') {
    lines.push('# Mux dormant rollback keys — leave unset unless rollback is declared.');
  }
  lines.push('');

  if (config.providers.email === 'resend') {
    lines.push('# ── Email — Resend (client account + verified sender domain) ────');
    lines.push(req('FROM must be on a verified domain.'));
    lines.push(`RESEND_API_KEY=${SECRET_PLACEHOLDER}`);
    lines.push(`EMAIL_FROM=${SECRET_PLACEHOLDER}`);
    lines.push(opt('support mailbox used as reply-to.'));
    lines.push(`EMAIL_REPLY_TO=${config.identity.supportEmail}`);
    lines.push(opt('enforce webhook signature verification.'));
    lines.push(`RESEND_WEBHOOK_SECRET=${SECRET_PLACEHOLDER}`);
    lines.push('');
  } else {
    lines.push('# ── Email — Resend DEFERRED (providers.email=none) ───────────────');
    lines.push('# Leave RESEND_API_KEY unset: app runs in STUB MODE (emails logged, never sent).');
    lines.push('# User creation is never blocked by missing email config.');
    lines.push('');
  }

  lines.push('# ── PDF generation (Puppeteer/Chrome) ──────────────────────────');
  lines.push(req('on Render: build postbuild downloads Chrome; the cache dir keeps it across build→runtime.'));
  lines.push('PUPPETEER_CACHE_DIR=/opt/render/project/src/apps/api/.puppeteer-cache');
  lines.push(opt('only for custom hosts with their own Chromium. Leave unset on Render.'));
  lines.push('# PUPPETEER_EXECUTABLE_PATH=<CUSTOM_HOST_ONLY>');
  lines.push('');

  lines.push('# ── ADMIN TOOLING ONLY — NEVER DEPLOY ──────────────────────────');
  lines.push('# SUPABASE_ACCESS_TOKEN* must NEVER appear in Render/Vercel env.');
  lines.push('# Zero references in apps/. Runtime was proven to work without it.');
  lines.push('');

  return lines.join('\n');
}

/** Vercel (Next.js web) environment template — build-time baked, redeploy after change. */
export function buildVercelEnvTemplate(config: ClientConfig): string {
  const { apiDomain, frontendDomain } = config.deployment;
  const lines: string[] = [header('Vercel web — environment template', config.client.name, config.client.deploymentId)];

  lines.push('# ALL THREE are REQUIRED and BUILD-TIME BAKED.');
  lines.push('# Changing any value requires a redeploy (Redeploy with existing build cache OFF is safest).');
  lines.push(req('public Render API origin — must equal the Render service URL.'));
  lines.push('# GENERATED FROM CLIENT CONFIG — paste as-is.');
  lines.push(`NEXT_PUBLIC_API_URL=${apiDomain}`);
  lines.push(req('client Supabase project URL — same value as Render SUPABASE_URL.'));
  lines.push(`NEXT_PUBLIC_SUPABASE_URL=${COPY_FROM_RENDER}`);
  lines.push(req('client Supabase anon key — same value as Render SUPABASE_ANON_KEY (public by design).'));
  lines.push(`NEXT_PUBLIC_SUPABASE_ANON_KEY=${COPY_FROM_RENDER}`);
  lines.push('');
  lines.push(`# Sanity: this deployment will be served at ${frontendDomain}`);
  lines.push(`# Render FRONTEND_URL must equal exactly: ${frontendDomain}`);
  lines.push('');

  return lines.join('\n');
}
