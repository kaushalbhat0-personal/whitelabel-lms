/**
 * Pre-flight verifier (operator machine).
 *
 * Checks: Node/pnpm versions, git state, migration continuity (001→040),
 * generated-SQL determinism (rebuild in memory, compare SHA-256 twice),
 * and that the generated artifact contains no secrets.
 *
 * Dirty git state is a WARN (runbook allows clean-or-known-dirty), never a
 * silent pass. Version/chain problems are FAILs with actionable messages.
 */

import * as fs from 'fs';
import * as path from 'path';
import * as crypto from 'crypto';
import { execFileSync } from 'child_process';
import { scanTextForSecrets } from './secret-scan';

export interface PreflightCheck {
  id: string;
  label: string;
  status: 'PASS' | 'FAIL' | 'WARN';
  detail: string;
}

/** Walk up from here until pnpm-workspace.yaml is found (repo root). */
export function findRepoRoot(startDir: string = __dirname): string {
  let dir = startDir;
  for (let i = 0; i < 8; i++) {
    if (fs.existsSync(path.join(dir, 'pnpm-workspace.yaml'))) return dir;
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error('Repo root not found (pnpm-workspace.yaml missing above ' + startDir + ')');
}

// Duplication note: EXPECTED_* pins the canonical boundary also enforced by
// scripts/generate-fresh-sql.ts. Both must agree; preflight fails if the
// migrations dir disagrees with EITHER side, so drift fails loudly.
export const EXPECTED_COUNT = 40;
export const EXPECTED_FIRST = '001_initial_schema.sql';
export const EXPECTED_LAST = '040_security_rls_hardening.sql';

function run(cmd: string, args: string[]): string | null {
  // Note: on Windows, pnpm/git are .cmd shims and require a shell to spawn.
  const opts = { encoding: 'utf-8', stdio: ['ignore', 'pipe', 'pipe'], shell: process.platform === 'win32' } as const;
  try {
    return execFileSync(cmd, args, opts).trim();
  } catch {
    return null;
  }
}

function major(v: string | null): number | null {
  if (!v) return null;
  const m = v.replace(/^v/, '').match(/^(\d+)\./);
  return m ? parseInt(m[1], 10) : null;
}

/** Rebuild the canonical artifact body in memory (same algorithm as the generator). */
export function rebuildFreshSql(migrationsDir: string, files: string[]): string {
  const parts: string[] = [
    '-- ============================================================',
    '-- White-Label LMS — Fresh Supabase Initialization',
    '-- GENERATED — DO NOT EDIT — source: scripts/migrations/001→040',
    '-- Generated by: pnpm db:generate (scripts/generate-fresh-sql.ts)',
    '-- ============================================================',
    '',
  ];
  for (const file of files) {
    const content = fs.readFileSync(path.join(migrationsDir, file), 'utf-8').trimEnd();
    parts.push('-- ============================================================');
    parts.push(`-- Migration: ${file}`);
    parts.push('-- ============================================================');
    parts.push('');
    parts.push(content);
    parts.push('');
  }
  return parts.join('\n') + '\n';
}

export function runPreflight(repoRoot: string = findRepoRoot()): { checks: PreflightCheck[]; overall: 'PASS' | 'FAIL' | 'WARN' } {
  const checks: PreflightCheck[] = [];
  const push = (id: string, label: string, status: PreflightCheck['status'], detail: string) =>
    checks.push({ id, label, status, detail });

  // Node / pnpm
  const nodeMajor = major(process.version);
  push('node-version', 'Node.js 20+', nodeMajor !== null && nodeMajor >= 20 ? 'PASS' : 'FAIL', `node ${process.version} (need >=20)`);
  const pnpmV = run('pnpm', ['--version']);
  const pnpmMajor = major(pnpmV);
  push(
    'pnpm-version', 'pnpm 8+',
    pnpmV === null ? 'FAIL' : pnpmMajor !== null && pnpmMajor >= 8 ? 'PASS' : 'FAIL',
    pnpmV === null ? 'pnpm not found on PATH' : `pnpm ${pnpmV} (need >=8)`,
  );

  // git state
  const head = run('git', ['rev-parse', 'HEAD']);
  const branch = run('git', ['branch', '--show-current']);
  const dirty = run('git', ['status', '--porcelain']);
  if (head === null) {
    push('git-state', 'Git state', 'FAIL', 'Not a git repo or git unavailable.');
  } else if (dirty && dirty.length > 0) {
    const files = dirty.split('\n').filter(Boolean).slice(0, 10).join(', ');
    push('git-state', 'Git state', 'WARN', `HEAD ${head} (${branch || '?'}), DIRTY: ${files}${dirty.split('\n').length > 10 ? '…' : ''} — reconcile with repo owner; factory output only.`);
  } else {
    push('git-state', 'Git state', 'PASS', `HEAD ${head} (${branch || 'detached'}), clean.`);
  }

  // migrations continuity
  const migrationsDir = path.join(repoRoot, 'scripts', 'migrations');
  const generatedFile = path.join(repoRoot, 'scripts', 'generated', 'fresh-supabase-init.sql');
  let canonical: string[] = [];
  if (!fs.existsSync(migrationsDir)) {
    push('migration-chain', 'Migrations 001→040', 'FAIL', `Missing dir: ${migrationsDir}`);
  } else {
    const files = fs.readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort();
    const missing: string[] = [];
    for (let i = 1; i <= EXPECTED_COUNT; i++) {
      const num = String(i).padStart(3, '0');
      const match = files.find((f) => f.startsWith(`${num}_`));
      if (!match) missing.push(`${num}_*.sql`);
      else canonical.push(match);
    }
    const unexpected = files.filter((f) => !canonical.includes(f));
    if (missing.length > 0) {
      push('migration-chain', 'Migrations 001→040', 'FAIL', `Missing: ${missing.join(', ')}`);
      canonical = [];
    } else if (unexpected.length > 0) {
      push('migration-chain', 'Migrations 001→040', 'FAIL', `Unexpected files outside 001→040: ${unexpected.join(', ')} — add via 041+ convention only.`);
      canonical = [];
    } else if (canonical[0] !== EXPECTED_FIRST || canonical[canonical.length - 1] !== EXPECTED_LAST) {
      push('migration-chain', 'Migrations 001→040', 'FAIL', `Boundary mismatch: ${canonical[0]} → ${canonical[canonical.length - 1]} (expect ${EXPECTED_FIRST} → ${EXPECTED_LAST})`);
      canonical = [];
    } else {
      push('migration-chain', 'Migrations 001→040', 'PASS', `${canonical.length} files, ${canonical[0]} → ${canonical[canonical.length - 1]}, contiguous.`);
    }
  }

  // determinism: rebuild twice in memory, compare with artifact
  if (canonical.length === EXPECTED_COUNT) {
    if (!fs.existsSync(generatedFile)) {
      push('sql-artifact', 'Generated SQL current', 'FAIL', `Missing ${generatedFile} — run pnpm db:generate.`);
    } else {
      const a = rebuildFreshSql(migrationsDir, canonical);
      const b = rebuildFreshSql(migrationsDir, canonical);
      const ha = crypto.createHash('sha256').update(a).digest('hex');
      const hb = crypto.createHash('sha256').update(b).digest('hex');
      const onDisk = fs.readFileSync(generatedFile, 'utf-8');
      const hd = crypto.createHash('sha256').update(onDisk).digest('hex');
      if (ha !== hb) {
        push('sql-artifact', 'Generated SQL current', 'FAIL', 'Non-deterministic rebuild (hashes differ between runs).');
      } else if (ha !== hd) {
        push('sql-artifact', 'Generated SQL current', 'FAIL', `Artifact stale: rebuilt sha256 ${ha.slice(0, 12)}… != on-disk ${hd.slice(0, 12)}… — run pnpm db:generate and review the diff.`);
      } else {
        push('sql-artifact', 'Generated SQL current', 'PASS', `Deterministic, current (sha256 ${hd.slice(0, 16)}…, ${Buffer.byteLength(onDisk, 'utf-8')} bytes).`);
        const secretHits = scanTextForSecrets(onDisk);
        push(
          'sql-secrets', 'Generated SQL has no secrets',
          secretHits.length === 0 ? 'PASS' : 'FAIL',
          secretHits.length === 0 ? 'No secret shapes detected.' : `Flagged: ${secretHits.map((f) => `${f.pattern}@L${f.line}`).join(', ')}`,
        );
      }
    }
  }

  const overall = checks.some((c) => c.status === 'FAIL') ? 'FAIL' : checks.some((c) => c.status === 'WARN') ? 'WARN' : 'PASS';
  return { checks, overall };
}
