/**
 * Deterministic generator for Supabase fresh DB initialization.
 *
 * Source: scripts/migrations/001_initial_schema.sql → 039_theme_json.sql
 * Artifact: scripts/generated/fresh-supabase-init.sql
 *
 * Rules:
 * - 001→039 exactly, contiguous, zero-padded, no gaps/duplicates
 * - Lexical sort == numeric sort (001…039)
 * - Fail on missing/duplicate/malformed
 * - Concatenate verbatim with deterministic headers, no timestamps
 * - No secrets, no env vars, no random IDs
 */

import * as fs from 'fs';
import * as path from 'path';

const MIGRATIONS_DIR = path.join(__dirname, 'migrations');
const GENERATED_DIR = path.join(__dirname, 'generated');
const GENERATED_FILE = path.join(GENERATED_DIR, 'fresh-supabase-init.sql');

const EXPECTED_COUNT = 39;
const EXPECTED_FIRST = '001_initial_schema.sql';
const EXPECTED_LAST = '039_theme_json.sql';

function fail(msg: string): never {
  console.error(`[generate-fresh-sql] ERROR: ${msg}`);
  process.exit(1);
}

function main() {
  if (!fs.existsSync(MIGRATIONS_DIR)) fail(`migrations dir not found: ${MIGRATIONS_DIR}`);

  const files = fs
    .readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith('.sql'))
    .sort(); // lexical, zero-pad guarantees numeric

  // Validate exact 001→039 contiguous
  const canonical: string[] = [];
  for (let i = 1; i <= EXPECTED_COUNT; i++) {
    const num = String(i).padStart(3, '0');
    const match = files.find((f) => f.startsWith(`${num}_`));
    if (!match) fail(`missing migration ${num}_*.sql (found: ${files.join(', ')})`);
    canonical.push(match);
  }

  // Check for unexpected files outside 001-039
  const expectedSet = new Set(canonical);
  const unexpected = files.filter((f) => !expectedSet.has(f));
  if (unexpected.length > 0) {
    fail(
      `unexpected migration files outside 001→039: ${unexpected.join(', ')} — ` +
        `expected exactly 001→039 (e.g., no 040,041,999,schema.sql in migrations/)`
    );
  }

  // Validate first/last
  if (canonical[0] !== EXPECTED_FIRST) fail(`first migration must be ${EXPECTED_FIRST}, got ${canonical[0]}`);
  if (canonical[canonical.length - 1] !== EXPECTED_LAST) fail(`last migration must be ${EXPECTED_LAST}, got ${canonical[canonical.length - 1]}`);

  // Validate no duplicates (numeric prefix)
  const prefixes = canonical.map((f) => f.slice(0, 3));
  const dup = prefixes.find((v, i) => prefixes.indexOf(v) !== i);
  if (dup) fail(`duplicate migration number ${dup}`);

  // Validate malformed filenames (must be NNN_name.sql)
  for (const f of canonical) {
    if (!/^\d{3}_[a-z0-9_]+\.sql$/.test(f)) fail(`malformed filename: ${f} (expected NNN_name.sql)`);
  }

  // Ensure generated dir exists
  if (!fs.existsSync(GENERATED_DIR)) fs.mkdirSync(GENERATED_DIR, { recursive: true });

  // Concatenate verbatim with deterministic headers
  const parts: string[] = [];
  parts.push('-- ============================================================');
  parts.push('-- White-Label LMS — Fresh Supabase Initialization');
  parts.push('-- GENERATED — DO NOT EDIT — source: scripts/migrations/001→039');
  parts.push('-- Generated by: pnpm db:generate (scripts/generate-fresh-sql.ts)');
  parts.push('-- ============================================================');
  parts.push('');

  for (const file of canonical) {
    const fullPath = path.join(MIGRATIONS_DIR, file);
    const content = fs.readFileSync(fullPath, 'utf-8').trimEnd();
    // Ensure file ends with single newline
    parts.push(`-- ============================================================`);
    parts.push(`-- Migration: ${file}`);
    parts.push(`-- ============================================================`);
    parts.push('');
    parts.push(content);
    parts.push(''); // blank line between migrations
  }

  const output = parts.join('\n') + '\n';
  fs.writeFileSync(GENERATED_FILE, output, 'utf-8');
  console.log(`[generate-fresh-sql] Generated ${GENERATED_FILE} from ${canonical.length} migrations (${canonical[0]} → ${canonical[canonical.length - 1]})`);
  console.log(`[generate-fresh-sql] Size: ${Buffer.byteLength(output, 'utf-8')} bytes`);
}

main();
